def name_tokens(name: str) -> set[str]:
    """Returns the set of comparable parts of a personal name: accents, case and
    punctuation are ignored, and a run of single-letter initials is joined into
    one token, so 'J. R. R.', 'J.R.R.' and 'JRR' all become 'jrr'.  Word order
    does not matter, so 'Tolkien, J. R. R.,' and 'J.R.R. Tolkien' give the same set."""
    words = re.findall(r"[^\W_]+", unicode_collapse(name))
    tokens: set[str] = set()
    initials = ""
    for w in words:
        if len(w) == 1:
            initials += w
        else:
            if initials:
                tokens.add(initials)
                initials = ""
            tokens.add(w)
    if initials:
        tokens.add(initials)
    return tokens


def author_match(lib_author, gr_author):
    return name_tokens(lib_author) <= name_tokens(gr_author)


def title_match(lib_title, gr_title):
    return unicode_collapse(lib_title) in unicode_collapse(gr_title)


# Goodreads requests share pacing, status handling, and XML parsing.
def get_goodreads_xml(session, url, operation, params=None):
    time.sleep(2)
    try:
        return get_xml(session, url, params=params)
    except RuntimeError as exc:
        raise RuntimeError(f"Goodreads {operation}: {exc}") from None


def goodreads_worknumber(session, author: str, title: str):
    url = "https://www.goodreads.com/search/index.xml"
    params = {
        "key": GOODREADS_API_KEY,
        "q": unicodedata.normalize("NFC", f"{author} {title}"),
    }
    response_data = get_goodreads_xml(session, url, "work search", params=params)
    results = response_data["GoodreadsResponse"]["search"]["results"]
    if not results:
        return None

    works = results["work"]
    if isinstance(works, list):
        for work in works:
            best_book = work["best_book"]
            gr_title = best_book["title"]
            gr_author = best_book["author"]["name"]
            if author_match(author, gr_author) and title_match(title, gr_title):
                break
        else:
            work = works[0]
    else:
        work = works
    return work["id"]["#text"]


def goodreads_seriesname(session, worknumber: str):
    url = f"https://www.goodreads.com/work/{worknumber}/series"
    params = {"format": "xml", "key": GOODREADS_API_KEY}
    response_data = get_goodreads_xml(session, url, "series lookup", params=params)
    seriesworks = response_data["GoodreadsResponse"]["series_works"]
    if not seriesworks:
        return None
    serieswork = seriesworks["series_work"]
    if isinstance(serieswork, list):
        serieswork = serieswork[0]
    return serieswork["series"]["title"]


NO_MATCH = "no match"


def normalize(text: str) -> str:
    return unicode_collapse(re.sub(r"[.,;:\s]+$", "", text).strip())


OTHER_SERIES_FIELDS = (("800", "t"), ("810", "t"), ("811", "t"), ("830", "a"))


def get_record_series(record) -> tuple[List[str], List[tuple[str, str]]]:
    """Return the 490 $a values and tagged series values from 8XX fields."""
    series_490 = [
        value
        for field in record.get_fields("490")
        for value in field.get_subfields("a")
    ]
    series_8xx = [
        (tag, value)
        for tag, code in OTHER_SERIES_FIELDS
        for field in record.get_fields(tag)
        for value in field.get_subfields(code)
    ]
    return series_490, series_8xx


def series_matches(goodreads_series: str, record_series: List[str]) -> bool:
    normalized_goodreads = normalize(goodreads_series)
    return any(normalized_goodreads == normalize(value) for value in record_series)


COLUMNS = ["Title", "Author", "Series from 490", "Series from 8XX", "Series from Goodreads"]


def is_proper_series(goodreads_series) -> str|None:
    if (goodreads_series not in (None, NO_MATCH)
        and isinstance(goodreads_series, str)
        and goodreads_series != ""):
        return goodreads_series
    else:
        return None


PROGRAM = "check-series"
VERSION = "0.7.1"


def main():
    parser = argparse.ArgumentParser(description="Compare Goodreads series info against MARC 490/8XX fields.")
    parser.add_argument("-i", "--input", required=True, help="MARC input file (required)")
    parser.add_argument(
        "-b",
        "--brief",
        action="store_true",
        help="only show rows with a proper Goodreads series name",
    )
    parser.add_argument("-o", "--output", required=True, help="Excel-compatible CSV output file (required)")
    parser.add_argument("-v", "--version", action="version", version=VERSION)
    args = parser.parse_args()

    if not GOODREADS_API_KEY:
        sys.exit("No Goodreads API key available.")

    print_terminal_header(PROGRAM, VERSION, args.input, args.output)
    processed = 0
    skipped = 0
    dispositions = Counter()

    with create_resilient_session() as session, open(args.input, "rb") as input_file, \
            open(args.output, "w", newline="", encoding="utf-8-sig") as output_file:
        session.headers.update({
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/111.0.0.0 Safari/537.36"
        })

        csv_writer = csv.writer(output_file)
        csv_writer.writerow(COLUMNS)

        reader = MARCReader(input_file)
        for record in reader:
            if record is None:
                skipped += 1
                continue
            processed += 1

            author_fields = record.get_fields("100")
            title_fields = record.get_fields("245")
            author_field = author_fields[0] if author_fields else None
            title_field = title_fields[0] if title_fields else None
            author = author_field.get("a") if author_field else None
            title = title_field.get("a") if title_field else None
            if title:
                title = title.rstrip(" :./=")

            if not author:
                dispositions["missing_author"] += 1
                if author_field is None and not args.brief:
                    csv_writer.writerow((title or "-", "None", "-", "-", "Skipped"))
                continue
            if not title:
                dispositions["missing_title"] += 1
                continue

            field_490, other_series = get_record_series(record)
            other_series_raw = [value for _, value in other_series]
            record_series = field_490 + other_series_raw
            if not record_series:
                dispositions["no_input_series"] += 1
                continue

            worknumber = goodreads_worknumber(session, author, title)
            if worknumber is None:
                dispositions["no_goodreads_work"] += 1
                goodreads_series = NO_MATCH
                proper_series = None
            else:
                goodreads_series = goodreads_seriesname(session, worknumber)
                proper_series = is_proper_series(goodreads_series)
                if not proper_series:
                    dispositions["goodreads_no_series"] += 1

            if proper_series and series_matches(proper_series, record_series):
                dispositions["series_match"] += 1
                continue

            if proper_series:
                dispositions["series_mismatch"] += 1

            if args.brief and not proper_series:
                continue

            display_490 = "; ".join(field_490) if field_490 else "-"
            display_other = "; ".join(f"({tag}) {value}" for tag, value in other_series) if other_series else "-"
            display_goodreads = goodreads_series if goodreads_series else "-"
            csv_writer.writerow((title, author, display_490, display_other, display_goodreads))

    print()
    print(f"{processed} records processed, {skipped} skipped (MARC parse failures)")
    print("Disposition totals:")
    for key, label in (
        ("missing_author", "Missing author"),
        ("missing_title", "Missing title"),
        ("no_input_series", "No series information in input record"),
        ("no_goodreads_work", "No matching Goodreads work"),
        ("goodreads_no_series", "Goodreads work has no series information"),
        ("series_match", "Series match"),
        ("series_mismatch", "Series mismatch"),
    ):
        print(f"  {label}: {dispositions[key]}")
    print("=" * 40)
    print(f"Detailed report written to: {args.output}\n")


if __name__ == "__main__":
    raise SystemExit(run_cli(main))
