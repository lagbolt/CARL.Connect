#
#    Reads records from a binary MARC file and, using the author and title information, gets series
#    information from Goodreads.  The Goodreads series name is compared
#    against the series information in the record's 490 field and its 800 $t, 810 $t, 811 $t and 830 $a
#    fields, if any.  A record is reported when at least one of these fields has a series name and the
#    Goodreads series name does not match any of them.
#
#    Usage:  python check-series.py -i <MARC input file> -o <output file> [-b]
#
#        -i,  --input     MARC input file (required)
#        -b,  --brief     only include rows with a Goodreads series name that differs from all
#                         series entries in the MARC record
#        -o,  --output    Excel-compatible CSV output file (required)
#
#    The CSV contains the reported record details.  Terminal output gives the input and output paths
#    and aggregate record disposition counts; it does not print record-specific details.
#    A record with no 100 $a author or no 245 $a title cannot be compared.  Records without series
#    information in the MARC entry are not sent to Goodreads.  Trailing spaces, colons, periods,
#    slashes and equals signs are stripped from the title.
