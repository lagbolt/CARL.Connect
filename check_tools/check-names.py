import argparse
import re
from typing import List, Set, Tuple

from fcpl_shared.common import unicode_collapse
from fcpl_shared.cli import configure_console, count_phrase, print_terminal_header
from pymarc import MARCReader, Record


configure_console()


PROGRAM = "check-names"
VERSION = "0.2.1"


# Utility functions

def summary_lines(total: int, skipped: int, duplicates: int) -> List[str]:
    return [
        f"{total} records processed, {skipped} skipped",
        f"{count_phrase(duplicates, 'possible duplicate name', 'possible duplicate names')} found",
    ]

def read_from_file(filename):
    """Yields each record in a binary MARC file, or None for a record that cannot be read."""
    with open(filename, 'rb') as marc_input:
        for aRecord in MARCReader(marc_input):
            yield aRecord


# *** Next four functions are concerned with harvesting author data
# *** from the $a and $d subfields of 100 and 700 fields so we
# *** can check for possible duplicates (e.g., Smith, Bob ~ Smith, Bob, 1972-)

def collect_authors(arecord: Record) -> Set[str]:
    """For each 100 and 700 field, the $a and $d subfields are jammed together
    into one string; author_split() separates them again later. Returns the
    authors found in this record."""
    authors: Set[str] = set()
    fields_100 = arecord.get_fields('100')
    if fields_100 and (a := fields_100[0].get('a')):
        afield = fields_100[0]
        d = afield.get('d')
        aname = a.rstrip(",.") + ("#" + d.rstrip(",.") if d else "")
        authors.add(aname)
    for f in arecord.get_fields('700'):
        if (a := f.get('a')):
            d = f.get('d')
            aname = a.rstrip(",.") + ("#" + d.rstrip(",.") if d else "")
            authors.add(aname)
    return authors

rgx = re.compile(r"(.*)(#\d{4}-)(\d{4})?$")
def author_split(author_string: str) -> Tuple:
    """Splits an author string into (name, birth date, death date), with
    missing values as None."""
    m = rgx.match(author_string)
    if not m:
        return author_string, None, None
    return m[1], m[2], m[3] if m.lastindex == 3 else None

def author_equals(x: str, y: str) -> bool:
    """Compares two (name, birth date, death date) tuples. Missing values
    match anything, so only two non-None, unequal values produce a False.
    Accents and case are ignored."""
    for ax, ay in zip(author_split(unicode_collapse(x)), author_split(unicode_collapse(y))):
        # ax and ay must be non-None to produce a false result
        if ax and ay and ax != ay:
            return False
    return True

def check_for_duplicate_authors(authors: Set[str]) -> List[str]:
    """Checks for duplicate authors in the supplied set. The set is
    sorted first (on the collapsed form of each name) so that possible
    duplicate pairs end up consecutive."""
    result: List[str] = []
    prev = "+++++"
    for author in sorted(authors, key=lambda a: (unicode_collapse(a), a)):
        if author_equals(author, prev):
            result.append(prev + " ~ " + author)
        prev = author
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description="Check a MARC file for possible duplicate author names.")
    parser.add_argument("-i", "--input", required=True, dest="inputfile",
                        help="Path to the binary MARC input file")
    parser.add_argument("-o", "--output", required=True, dest="outputfile",
                        help="Path to the output report file")
    args = parser.parse_args()

    print_terminal_header(PROGRAM, VERSION, args.inputfile, args.outputfile)

    total_records = 0
    skipped_records = 0
    authors: Set[str] = set()
    for theRecord in read_from_file(args.inputfile):
        if theRecord is None:
            skipped_records += 1
            continue
        total_records += 1
        authors.update(collect_authors(theRecord))

    duplicate_authors = check_for_duplicate_authors(authors)
    summary = summary_lines(total_records, skipped_records, len(duplicate_authors))

    with open(args.outputfile, 'w', encoding='utf-8') as out_f:
        out_f.write(f"# {PROGRAM} {VERSION}\n")
        out_f.write(f"# Input:  {args.inputfile}\n")
        out_f.write(f"# Output: {args.outputfile}\n")
        out_f.write(f"# Possible duplicate authors in {args.inputfile}\n")
        out_f.write("# " + "-" * 72 + "\n")
        if duplicate_authors:
            for pair in duplicate_authors:
                out_f.write(pair + "\n")
        else:
            out_f.write("# No possible duplicate authors found\n")
        out_f.write("# " + "-" * 72 + "\n")
        for line in summary:
            out_f.write(f"# {line}\n")

    for line in summary:
        print(line)
    print(f"Detailed report written to: {args.outputfile}\n")


if __name__ == "__main__":
    main()
