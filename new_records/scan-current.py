#
#    Scan recent titles from the FCPL catalog and record new
#    titles in new-titles.db. Titles are classified by whether the title text is
#    all upper case (UC) or mixed case (MC):
#      - A UC title not yet in the database is added with status = Pending.
#      - An MC title not yet in the database is added with status = Done, and its
#        MARC record (fetched via get_one_marc) is written to the MARC output file.
#      - A UC title already in the database with status = Pending is skipped.
#      - An MC title already in the database with status = Pending replaces that
#        row entirely (including a fresh date_stamp) with status = Done, and its
#        MARC record is written to the MARC output file.
#      - An MC title already in the database with status = Done is skipped.
#      - A UC title already in the database with status = Done prints a warning
#        and leaves the database unchanged.
#
#    Usage:  python scan-current.py
#                [ -o <MARC output file> ]
#                [ -q <search term> ]
#
#    The -o/--output argument gives the path of the MARC output file that
#    records are written to for MC titles. Defaults to new-records.mrc next to
#    this script.
#
#    The -q/--query argument gives the search term to use in place of the
#    default "callnumber:%/[A-Za-z0-9]/". Facet filters (book, last two weeks) are unchanged.
#
#    Prints a database status summary before and after the scan, and a count of
#    each kind of operation performed during the scan.
#
