import argparse
import sqlite3
from collections import Counter
from pathlib import Path

from pymarc import MARCWriter

from fcpl_shared.common import HTTP_HEADERS, create_resilient_session, get_resource
from fcpl_shared.account import ListItem
from fcpl_shared.cli import run_cli
from fcpl_shared.marc import get_one_marc
from fcpl_shared.search import SearchPayload, build_facet_filters, iter_ids

DB_PATH = Path(__file__).resolve().parent / "new-titles.db"
MARC_OUTPUT_PATH = Path(__file__).resolve().parent / "new-records.mrc"
ID_LIMIT = 101  # same as records.py -f 101

STATUSES = ("Pending", "Done")

CREATE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS new_titles (
    item_id TEXT NOT NULL PRIMARY KEY,
    short_title TEXT NOT NULL DEFAULT 'Dummy Title',
    short_author TEXT NOT NULL DEFAULT 'Dummy Author',
    pub_date TEXT NOT NULL DEFAULT '0000',
    format TEXT NOT NULL DEFAULT '',
    date_stamp TEXT NOT NULL DEFAULT (datetime('now')),
    status TEXT NOT NULL DEFAULT 'New'
        CHECK (status IN ('Pending', 'New', 'Done'))
)
"""

# Operation key -> display label, in the order they should be reported.
OPERATIONS = (
    ("added_pending", "Added new UC title (status = Pending)"),
    ("added_done", "Added new MC title (status = Done, record written)"),
    ("updated_done", "Updated status from Pending to Done (record written)"),
    ("skipped", "Skipped (already processed)"),
    ("warning", "Warning (UC title already Done)"),
)


def ensure_table(con):
    """Creates the new_titles table if it does not already exist."""
    con.execute(CREATE_TABLE_SQL)
    con.commit()


def print_db_summary(con):
    counts = dict(
        con.execute("SELECT status, COUNT(*) FROM new_titles GROUP BY status").fetchall()
    )
    print(f"Database: {DB_PATH.name} ({sum(counts.values())} rows)")
    for status in STATUSES:
        print(f"  {status}: {counts.get(status, 0)}")
    for status, count in counts.items():
        if status not in STATUSES:
            print(f"  {status}: {count}")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Scan recent title and record new titles in new-titles.db."
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=MARC_OUTPUT_PATH,
        help="MARC output file for MC title records (default: %(default)s)",
    )
    parser.add_argument(
        "-q",
        "--query",
        default=r"callnumber:%/[A-Za-z0-9]/",
        help=r"Search term to use in place of the default: %(default)s",
    )
    return parser.parse_args()


def main():
    args = parse_args()

    search = SearchPayload(
        args.query,
        facet_filters=build_facet_filters(book=True, last_two_weeks=True),
    )

    saw_id_limit = False
    operations = Counter()

    with create_resilient_session() as s:
        s.headers.update(HTTP_HEADERS)
        con = sqlite3.connect(DB_PATH)
        ensure_table(con)

        print_db_summary(con)
        print()

        with open(args.output, "ab") as marc_out:
            writer = MARCWriter(marc_out)

            for index, item_id in enumerate(iter_ids(s, search, limit=ID_LIMIT), start=1):
                if index == ID_LIMIT:
                    saw_id_limit = True
                    print("Warning: Unlikely number of results returned")
                    print(f"Discarded id: {item_id}")
                    break

                resource = get_resource(s, item_id)
                list_item = ListItem.from_resource(resource)
                is_uc_title = list_item.short_title.isupper()

                existing = con.execute(
                    "SELECT status FROM new_titles WHERE item_id = ?",
                    (list_item.item_id,),
                ).fetchone()

                if existing is None:
                    # New item: UC titles start Pending. MC titles are considered
                    # fully cataloged immediately, so they start Done and their
                    # MARC record is written out.
                    status = "Pending" if is_uc_title else "Done"
                    if not is_uc_title:
                        writer.write(get_one_marc(s, item_id))
                    con.execute(
                        """
                        INSERT INTO new_titles (
                            item_id, short_title, short_author, pub_date, format, status
                        ) VALUES (?, ?, ?, ?, ?, ?)
                        """,
                        (
                            list_item.item_id,
                            list_item.short_title,
                            list_item.short_author,
                            list_item.pub_date,
                            list_item.format,
                            status,
                        ),
                    )
                    con.commit()
                    print(f"{list_item} ... {status.lower()}")
                    operations["added_pending" if is_uc_title else "added_done"] += 1
                    continue

                existing_status = existing[0]

                if is_uc_title:
                    if existing_status == "Pending":
                        print(f"{list_item} ... skipped")
                        operations["skipped"] += 1
                    else:
                        print(f"{list_item} ... warning (already {existing_status.lower()})")
                        operations["warning"] += 1
                    continue

                # Mixed-case title.
                if existing_status != "Pending":
                    print(f"{list_item} ... skipped")
                    operations["skipped"] += 1
                    continue

                # Mixed-case title replaces a Pending (placeholder UC) row entirely,
                # including a fresh date_stamp, and is now considered Done.
                writer.write(get_one_marc(s, item_id))
                con.execute(
                    """
                    INSERT OR REPLACE INTO new_titles (
                        item_id, short_title, short_author, pub_date, format, status
                    ) VALUES (?, ?, ?, ?, ?, 'Done')
                    """,
                    (
                        list_item.item_id,
                        list_item.short_title,
                        list_item.short_author,
                        list_item.pub_date,
                        list_item.format,
                    ),
                )
                con.commit()
                print(f"{list_item} ... replaced")
                operations["updated_done"] += 1

        if not saw_id_limit:
            new_entries = operations["added_pending"] + operations["added_done"]
            print(f"\n{new_entries} new records added to the database.")
            print(f"{operations['updated_done']} Pending records changed to Done.")

        print("\nOperations performed:")
        for key, label in OPERATIONS:
            print(f"  {label}: {operations[key]}")

        print()
        print_db_summary(con)

        con.close()


if __name__ == "__main__":
    raise SystemExit(run_cli(main))
