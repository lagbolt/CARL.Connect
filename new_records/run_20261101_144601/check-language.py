#
#    Reads MARC records and checks language coding for consistency across the 008 (positions
#    35-37), 041, 240 $l, 546, and 700 $e/$l fields. Flags cases such as an 008 language code
#    that disagrees with the 041 or 240 $l, translations that are missing expected 041/546
#    indicators, and bilingual/multilingual titles whose notes or subject headings don't reflect it.
#
#    Usage:  python check-language.py
#               -i <MARC input file (.mrc)>
#               -o <output report file>
#               [ -b ]
#
#    -i, --input   Path to the binary input MARC file (.mrc). Required.
#    -o, --output  Path to the output text report file. Required.
#    -b, --brief   Limit the output file to records with serious and non-serious errors.
