def get_008_language(record: Record) -> str:
    """Returns the 3-character language code from 008 positions 35-37, or ''
    if the 008 is missing, too short, blank at that position, or filled with
    '|||' (the fill character, meaning no attempt was made to code it)."""
    f008 = record.get('008')
    if f008 and len(f008.data) >= 38: # type: ignore
        code = f008.data[35:38].strip() # type: ignore
        return '' if code == '|||' else code
    return ''


def get_bibnumber(record: Record) -> str:
    """Returns the record's 001, else the 035 $a, else ''."""
    if v := record.get('001'):
        return v.data # type: ignore
    if (f := record.get('035')) and (v := f.get('a')):
        return v # type: ignore
    return ''


def get_responsibility(record: Record) -> str:
    """Returns a clean display string combining the 245 $a title and $c
    statement of responsibility, or a fallback string if there's no 245."""
    f245 = record.get('245')
    if not f245:
        return "Unknown Title"

    title = f245.get('a', default="Unknown Title")
    if not title:
        return "Unknown Title"
    title = title.rstrip(' /:,')

    responsibility = f245.get('c', default='')
    if responsibility:
        return f"{title} / {responsibility.rstrip(' .')}"
    return title


def normalize_lang_text(text: str) -> str:
    """Strips whitespace and a trailing period, and casefolds, so free-text
    language mentions (e.g. from 240 $l) can be compared reliably."""
    return text.strip().rstrip('.').strip().casefold()


def langs_match(a: Optional[str], b: Optional[str]) -> bool:
    """Case- and punctuation-insensitive comparison of two language names."""
    if not a or not b:
        return False
    return normalize_lang_text(a) == normalize_lang_text(b)


def check_translation_indicators(record: Record, f240_fields: Optional[list[Field]] = None) -> bool:
    """Checks various fields for indications that the work is a translation."""
    # Check 041 $h
    for f in record.get_fields('041'):
        if f.get_subfields('h'):
            return True

    # Check 245 $c
    for f in record.get_fields('245'):
        for sf in f.get_subfields('c'):
            if re.search(r'translat(ed|ion|or)', sf, re.IGNORECASE):
                return True

    # Check 546
    for f in record.get_fields('546'):
        if f.value() and re.search(r'translat(ed|ion|or)', f.value(), re.IGNORECASE):
            return True

    # Check 700 $e
    for f in record.get_fields('700'):
        for sf in f.get_subfields('e'):
            if re.search(r'translator', sf, re.IGNORECASE):
                return True

    # Check 240 $l (accepts already-fetched fields to avoid re-querying the record)
    for f in (f240_fields if f240_fields is not None else record.get_fields('240')):
        if f.get_subfields('l'):
            return True

    return False


def language_codes(f041: Optional[Field]) -> set[str]:
    if f041 is None:
        return set()
    return {sf.value for sf in f041.subfields if (sf.code.isalpha() and sf.code not in {'h', 'k'})}


def field_search(search_pattern: str, fields: list[Field]) -> bool:
    for f in fields:
        if re.search(search_pattern, f.value(), re.IGNORECASE):
            return True
    return False


def check_008_vs_041_vs_240(lang_code_from_008: str, f041: Field, lang_from_240l: Optional[str]) -> list[Issue]:
    """Cross-checks the 008 language code, the 041, and the 240 $l against each other."""
    if lang_code_from_008 == "mul":
        return []

    issues: list[Issue] = []
    lang_008_name = language_pairs.get(lang_code_from_008)

    # Does the 240 $l text agree with the language named by the 008?
    if langs_match(lang_from_240l, lang_008_name):
        error_severity_041 = Severity.WARNING
    else:
        error_severity_041 = Severity.NONSERIOUS
        # 240 $l disagrees with 008 -- try to work out which one is likely wrong
        if lang_from_240l:
            f041_first_lang = language_pairs.get(f041.subfields[0].value) if f041.subfields else None
            if f041_first_lang:
                f041h_lang = language_pairs.get(f041.get('h', default='xxx')) # type: ignore
                if lang_008_name == f041h_lang and langs_match(f041_first_lang, lang_from_240l):
                    issues.append(Issue("008 != 240 $l; 008 appears wrong", Severity.SERIOUS))
                elif lang_008_name == f041_first_lang:
                    issues.append(Issue("008 != 240 $l; 240 $l appears wrong", Severity.NONSERIOUS))
                else:
                    issues.append(Issue("008 != 240 $l; unknown cause", Severity.NONSERIOUS))
            else:
                issues.append(Issue("008 != 240 $l; unknown cause", Severity.NONSERIOUS))

    # Does the 008 language code actually show up in the 041, and is it first?
    subfields_by_code = f041.subfields_as_dict()
    codes_containing_008_lang = [code for code, values in subfields_by_code.items()
                                  if lang_code_from_008 in values]

    if not codes_containing_008_lang:
        issues.append(Issue("The language in the 008 field does not appear in the 041", error_severity_041))
    elif codes_containing_008_lang == ['h']:
        issues.append(Issue("The language in the 008 field only appears in the 041 $h subfield", error_severity_041))
    elif f041.subfields and f041.subfields[0].value == lang_code_from_008:
        pass  # 008 language is first in the 041 -- all good
    else:
        issues.append(Issue("The language in the 008 field appears in an 041 subfield, but is not first",
                             Severity.WARNING))

    return issues


def validate_record(record: Record) -> RecordResult:
    """Applies language consistency rules to a single MARC record."""
    issues: list[Issue] = []

    def add_issue(msg: str, severity: Severity = Severity.SERIOUS) -> None:
        issues.append(Issue(msg, severity))

    title = get_responsibility(record)

    # 1. Extract 008 language code
    lang_code_008 = get_008_language(record)
    if not lang_code_008:
        add_issue("008 language code is missing.")
    elif len(lang_code_008) != 3:
        add_issue("008 language code is not three characters.")

    # 2. Extract 041 subfields (use only the first 041)
    f041_fields = record.get_fields('041')
    if len(f041_fields) > 1:
        add_issue(f"Record contains {len(f041_fields)} 041 fields; only the first 041 was evaluated.",
                  Severity.WARNING)

    f041 = f041_fields[0] if f041_fields else None
    if f041 and any(len(sf.value) != 3 for sf in f041.subfields if sf.code.isalpha()):
        add_issue("041 language code is not three characters.")

    # 3. Check: 008 vs 041 vs 240 $l
    f240_fields = record.get_fields('240')
    f240 = f240_fields[0] if f240_fields else None
    lang_from_240 = f240.get('l', default='') if f240 else ''

    if f041 and lang_code_008:
        for issue in check_008_vs_041_vs_240(lang_code_008, f041, lang_from_240):
            issues.append(issue)

    # 4. Check for translations and multiple languages
    f546_fields = record.get_fields('546')
    notes_fields = record.notes
    subjects_fields = record.subjects

    if check_translation_indicators(record, f240_fields=f240_fields):
        if not f041:
            add_issue("Record indicates a translation, but 041 is missing.", Severity.WARNING)
        else:
            if not f041.get_subfields('h'):
                add_issue("Record indicates a translation, but 041 is missing the $h (original language) subfield.",
                          Severity.WARNING)
            if f041.indicator1 != "1":
                add_issue("Record indicates a translation, but the first indicator of 041 is not 1.",
                          Severity.WARNING)

        if not f546_fields:
            add_issue("Record indicates a translation, but no 546 language note is present.", Severity.WARNING)
        elif not field_search(r'translat(ed|ion|or)', f546_fields):
            add_issue("Record indicates a translation, but the 546 does not mention it.", Severity.WARNING)

    langs = language_codes(f041)
    if len(langs) == 2:
        # Item is bilingual
        bilingual_not_in_notes = not field_search(r'bilingual', notes_fields)
        bilingual_not_in_subjects = not field_search(r'bilingual', subjects_fields)
        all_languages_in_notes = True
        for code in langs:
            language_name = language_pairs.get(code)
            if not language_name or not field_search(language_name, notes_fields):
                all_languages_in_notes = False
                break

        if (not all_languages_in_notes) and bilingual_not_in_notes and bilingual_not_in_subjects:
            add_issue("Title is bilingual, but notes do not mention languages "
                      "and no bilingual subject heading is present.")
        elif bilingual_not_in_notes and bilingual_not_in_subjects:
            add_issue("Title is bilingual, but neither notes nor subjects mentions it.", Severity.NONSERIOUS)
        elif bilingual_not_in_notes:
            add_issue("Title is bilingual, but notes do not mention it.", Severity.WARNING)
        elif bilingual_not_in_subjects:
            add_issue("Title is bilingual, but no bilingual subject heading is present.", Severity.WARNING)

    elif len(langs) > 2:
        # multiple languages
        if not f546_fields:
            add_issue("Multiple languages in 041, but no 546 language note is present to explain them.",
                      Severity.WARNING)
        # Note: Checking exact matches between 3-letter codes in 041 and free text in 546 is inexact.
        # This ensures the 546 is at least present to describe the multiple languages.

    return RecordResult(
        title=title,
        lang_008=lang_code_008,
        f041_fields=f041_fields,
        f240_fields=f240_fields,
        f546_fields=f546_fields,
        record=record,
        issues=issues,
    )


PROGRAM = "check-language"
VERSION = "0.4.0"


def print_terminal_header(program: str, version: str, inputfile: str, outputfile: str) -> None:
    print("=" * 45)
    print(f"  {program} {version}")
    print(f"  Input:  {inputfile}")
    print(f"  Output: {outputfile}")
    print("=" * 45)


def count_phrase(n: int, singular: str, plural: str) -> str:
    return f"{n} {singular if n == 1 else plural}"


def summary_lines(total: int, skipped: int, errors: int, error_records: int) -> List[str]:
    return [
        f"{total} records processed, {skipped} skipped",
        f"{count_phrase(errors, 'error', 'errors')} found in {count_phrase(error_records, 'record', 'records')}",
    ]


def main() -> None:
    parser = argparse.ArgumentParser(description="Check MARC records for language coding consistency.")
    parser.add_argument("-i", "--input", required=True, dest="input",
                         help="Path to the binary input MARC file (.mrc)")
    parser.add_argument("-o", "--output", required=True, dest="output",
                         help="Path to the output text report file")
    parser.add_argument("-b", "--brief", action="store_true", dest="brief",
                         help="Limit output file to records with serious and non-serious errors")
    args = parser.parse_args()

    serious_counter: Counter = Counter()
    nonserious_counter: Counter = Counter()
    warning_counter: Counter = Counter()
    total_records = 0
    skipped_records = 0
    errors_found = 0
    records_with_errors = 0
    records_with_serious_errors = 0
    records_with_nonserious_errors = 0
    records_with_only_warnings = 0

    try:
        print_terminal_header(PROGRAM, VERSION, args.input, args.output)
        with open(args.input, 'rb') as in_f, open(args.output, 'w', encoding='utf-8') as out_f:
            out_f.write(f"# {PROGRAM} {VERSION}\n")
            out_f.write(f"# Input:  {args.input}\n")
            out_f.write(f"# Output: {args.output}\n")
            out_f.write("# Language Consistency Report\n")
            out_f.write("# " + "=" * 72 + "\n\n")

            reader = MARCReader(in_f)

            for position, record in enumerate(reader, start=1):
                if record is None:
                    skipped_records += 1
                    print(f"Warning: Could not parse record {position}: {reader.current_exception}")
                    continue
                total_records += 1

                try:
                    result = validate_record(record)
                except Exception as exc:
                    print(f"Warning: Error validating record {position}: {exc}")
                    continue

                if not result.issues:
                    continue

                errors_found += len(result.issues)
                records_with_errors += 1

                if result.has_serious:
                    records_with_serious_errors += 1
                elif result.has_nonserious:
                    records_with_nonserious_errors += 1
                elif result.has_warning:
                    records_with_only_warnings += 1

                for issue in result.issues:
                    if issue.severity == Severity.SERIOUS:
                        serious_counter[issue.message] += 1
                    elif issue.severity == Severity.NONSERIOUS:
                        nonserious_counter[issue.message] += 1
                    elif issue.severity == Severity.WARNING:
                        warning_counter[issue.message] += 1

                if result.has_serious or result.has_nonserious or not args.brief:
                    out_f.write(f"Record {position} ({get_bibnumber(record)}): {result.title}\n")
                    for issue in result.issues:
                        out_f.write(f"    [{issue.severity.value}] {issue.message}\n")

                    # lang_008 is '' whenever the 008 is missing, too short, or
                    # blank at positions 35-37 -- report all of those as "None".
                    out_f.write(f"    008 language: {result.lang_008 or 'None'}\n")

                    if result.f041_fields:
                        for f in result.f041_fields:
                            out_f.write(f"    {f}\n")
                    else:
                        out_f.write("    041: None\n")
                    for f in result.f240_fields:
                        out_f.write(f"    {f}\n")
                    for f in result.f546_fields:
                        out_f.write(f"    {f}\n")
                    for f in result.record.get_fields('700'):
                        if f.get_subfields('l', 'L'):
                            out_f.write(f"    {f}\n")

                    out_f.write("\n")

            out_f.write("\n# " + "=" * 72 + "\n")
            for line in summary_lines(total_records, skipped_records, errors_found, records_with_errors):
                out_f.write(f"# {line}\n")

        # Print summary to terminal
        for line in summary_lines(total_records, skipped_records, errors_found, records_with_errors):
            print(line)
        print(f"  {count_phrase(records_with_serious_errors, 'record with', 'records with')} serious errors")
        print(f"  {count_phrase(records_with_nonserious_errors, 'record whose', 'records whose')} "
              f"worst issue is non-serious")
        print(f"  {count_phrase(records_with_only_warnings, 'record with', 'records with')} only warnings")
        print("-" * 40)
        if not serious_counter and not nonserious_counter and not warning_counter:
            print("Excellent! No language inconsistencies found.")
        else:
            print("Serious Errors:")
            if serious_counter:
                for error, count in serious_counter.items():
                    print(f"[{count:4d}] {error}")
            else:
                print("  None")
            print("\nNon-Serious Errors:")
            if nonserious_counter:
                for error, count in nonserious_counter.items():
                    print(f"[{count:4d}] {error}")
            else:
                print("  None")
            print("\nWarnings:")
            if warning_counter:
                for error, count in warning_counter.items():
                    print(f"[{count:4d}] {error}")
            else:
                print("  None")
        print("=" * 40)
        print(f"Detailed report written to: {args.output}\n")

    except (FileNotFoundError, PermissionError) as exc:
        kind = "input" if exc.filename == args.input else "output"
        print(f"Error: Could not open the {kind} file '{exc.filename}': {exc.strerror}.")
        sys.exit(1)


if __name__ == "__main__":
    main()
