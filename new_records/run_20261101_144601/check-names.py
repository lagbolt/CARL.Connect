#
#    Reads a binary MARC file and checks for possible duplicate author names in the 100 and 700
#    fields (e.g., "Smith, Bob" ~ "Smith, Bob, 1972-").  Names are compared after accents and case
#    have been removed (see unicode_collapse), so "García, Ana" and "Garcia, Ana" count as possible
#    duplicates, as do precomposed and decomposed forms of the same accented character.
#
#    Usage:  python check-names.py -i <MARC input file> -o <output file>
#
#    -i, --input   Path to the binary MARC input file. Required.
#    -o, --output  Path to the output report file. Required.
#
#    Each possible duplicate pair is written to the output file as "name1 ~ name2", where the birth
#    and death dates (if any) follow a '#' in the name.  The terminal shows only the summary.
#
#    Generated by Claude.
#
