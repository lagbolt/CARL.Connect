# Unicode helper functions

def unicode_collapse(s: str) -> str:
    """Returns s with accents removed and case folded, in canonical (NFC) form,
    so strings that differ only in accents, case, or precomposed versus
    decomposed characters compare equal.

    Note: only characters that decompose into a base letter plus combining marks
    are affected.  Letters such as 'ø', 'đ' and 'ł' have no such decomposition
    and are left alone."""
    s = unicodedata.normalize("NFD", s)
    s = s.casefold()
    # casefold can introduce new combining marks (e.g. 'İ' -> 'i' + U+0307),
    # so decompose again before stripping them.
    s = unicodedata.normalize("NFD", s)
    s = "".join(c for c in s if not unicodedata.combining(c))
    return unicodedata.normalize("NFC", s)


def name_tokens(name: str) -> set[str]:
    """Returns the set of comparable parts of a personal name: accents, case and
    punctuation are ignored, and a run of single-letter initials is joined into
    one token, so 'J. R. R.', 'J.R.R.' and 'JRR' all become 'jrr'.  Word order
    does not matter, so 'Tolkien, J. R. R.,' and 'J.R.R. Tolkien' give the same set."""
    words = re.findall(r"[^\W_]+", unicode_collapse(name))
    tokens: set[str] = set()
    initials = ""
    for w in words:
        if len(w) == 1:
            initials += w
        else:
            if initials:
                tokens.add(initials)
                initials = ""
            tokens.add(w)
    if initials:
        tokens.add(initials)
    return tokens


def author_match(lib_author, gr_author):
    return name_tokens(lib_author) <= name_tokens(gr_author)


def title_match(lib_title, gr_title):
    return unicode_collapse(lib_title) in unicode_collapse(gr_title)


# The Goodreads API returns deeply nested XML, so we have to do some
# work to extract the few values we need, first converting to JSON.

def goodreads_worknumber(session, author:str, title:str, debug=False):
    time.sleep(2)
    url = f"https://www.goodreads.com/search/index.xml?key="+ GOODREADS_API_KEY
    params = { 'q' : unicodedata.normalize("NFC", f"{author} {title}") }
    response = session.get(url, params=params)
    try:
        response.raise_for_status()
    except requests.HTTPError as e:
        print(f"Error in get_worknumber(author={author!r}, title={title!r}): {e}")
        print(f"URL: {url}")
        print(f"Params: {params}")
        raise
    if debug:
        print(f"response in get_worknumber: {response.text}")
    if (results := xmltodict.parse(response.content)['GoodreadsResponse']['search']['results']):
        works = results['work']
        if isinstance(works, list):
            for work in works:
                best_book = work['best_book']
                gr_title = best_book['title']
                gr_author = best_book['author']['name']
                if author_match(author, gr_author) and title_match(title, gr_title):
                    break
            else:
                work = works[0]
        else:
            work = works
        return work['id']['#text']

    else:
        if debug:
            print("No author title match in get_worknumber")
        return None


def goodreads_seriesname(session, worknumber: str, debug=False):
    time.sleep(2)
    url = f"https://www.goodreads.com/work/{worknumber}/series?format=xml&key=" + GOODREADS_API_KEY
    response = session.get(url)
    try:
        response.raise_for_status()
    except requests.HTTPError as e:
        print(f"Error in get_seriesname(worknumber={worknumber!r}): {e}")
        print(f"URL: {url}")
        raise
    seriesworks = xmltodict.parse(response.content)['GoodreadsResponse']['series_works']
    if debug:
        print(f"seriesworks in get_seriesname:\n{seriesworks}")
    if not seriesworks:
        return None
    serieswork = seriesworks['series_work']
    if isinstance(serieswork, list):
        serieswork = serieswork[0]
    return serieswork['series']['title']



NO_MATCH = "no match"


def enabled():
    return bool(GOODREADS_API_KEY)


def normalize(text: str) -> str:
    return unicode_collapse(re.sub(r"[.,;:\s]+$", "", text).strip())


def get_subfield_values(record, tag: str, code: str) -> List[str]:
    values = []
    for field in record.get_fields(tag):
        values.extend(field.get_subfields(code))
    return values


OTHER_SERIES_FIELDS = [("800", "t"), ("810", "t"), ("811", "t"), ("830", "a")]


def get_tagged_series_values(record) -> List[tuple]:
    values = []
    for tag, code in OTHER_SERIES_FIELDS:
        for field in record.get_fields(tag):
            for value in field.get_subfields(code):
                values.append((tag, value))
    return values


def series_matches(goodreads_series: str, record_series: List[str]) -> bool:
    normalized_goodreads = normalize(goodreads_series)
    return any(normalized_goodreads == normalize(value) for value in record_series)


COLUMNS = ["Title", "Author", "Series from 490", "Series from 8XX", "Series from Goodreads"]


def make_row_table(show_header: bool) -> Table:
    table = Table(show_header=show_header, expand=True, box=None, pad_edge=False)
    for name in COLUMNS:
        table.add_column(name, ratio=1, overflow="fold")
    return table


def print_header(console: Console) -> None:
    table = make_row_table(show_header=True)
    console.print(table)
    console.rule(style="dim")


def print_row(console: Console, cells) -> None:
    table = make_row_table(show_header=False)
    table.add_row(*(Text(cell) for cell in cells))
    console.print(table)
    console.rule(style="dim")


def emit_row(console: Console, csv_writer, cells, show_console: bool) -> None:
    if show_console:
        print_row(console, cells)
    if csv_writer is not None:
        csv_writer.writerow(cells)


def has_proper_series(goodreads_series) -> bool:
    return goodreads_series not in (None, NO_MATCH) and goodreads_series != ""


PROGRAM = "check-series"
VERSION = "0.7.1"


def print_terminal_header(program: str, version: str, inputfile: str, outputfile: str) -> None:
    print("=" * 45)
    print(f"  {program} {version}")
    print(f"  Input:  {inputfile}")
    print(f"  Output: {outputfile}")
    print("=" * 45)


def count_phrase(n: int, singular: str, plural: str) -> str:
    return f"{n} {singular if n == 1 else plural}"


def summary_lines(total: int, skipped: int, mismatches: int) -> List[str]:
    return [
        f"{total} records processed, {skipped} skipped",
        f"Series mismatch in {count_phrase(mismatches, 'record', 'records')}",
    ]


def main():
    parser = argparse.ArgumentParser(description="Compare Goodreads series info against MARC 490/8XX fields.")
    parser.add_argument("-i", "--input", required=True, help="MARC input file (required)")
    parser.add_argument(
        "-b",
        "--brief",
        action="store_true",
        help="only show rows with a proper Goodreads series name",
    )
    parser.add_argument("-o", "--output", required=True, help="Excel-compatible CSV output file (required)")
    parser.add_argument("-v", "--version", action="version", version=VERSION)
    args = parser.parse_args()

    if not enabled():
        sys.exit("No Goodreads API key available.")

    console = Console()
    print_terminal_header(PROGRAM, VERSION, args.input, args.output)

    processed = 0
    skipped = 0
    mismatches = 0

    with requests.Session() as session, open(args.input, "rb") as fh, \
            open(args.output, "w", newline="", encoding="utf-8-sig") as output_file:
        session.headers.update({
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/111.0.0.0 Safari/537.36"
        })

        csv_writer = csv.writer(output_file)
        csv_writer.writerow(COLUMNS)
        output_file.write(f"# {PROGRAM} {VERSION}\n")
        output_file.write(f"# Input:  {args.input}\n")
        output_file.write(f"# Output: {args.output}\n")

        reader = MARCReader(fh)
        for record in reader:
            if record is None:
                skipped += 1
                continue
            processed += 1

            author_fields = record.get_fields("100")
            title_fields = record.get_fields("245")
            author_field = author_fields[0] if author_fields else None
            title_field = title_fields[0] if title_fields else None

            title = title_field.get("a") if title_field else None
            if title:
                title = title.rstrip(" :./=")

            if author_field is None:
                if not args.brief:
                    emit_row(console, csv_writer, (title or "-", "None", "-", "-", "Skipped"), False)
                continue

            author = author_field.get("a")
            if not author or not title:
                continue

            field_490 = get_subfield_values(record, "490", "a")
            other_series = get_tagged_series_values(record)
            other_series_raw = [value for _, value in other_series]
            if not field_490 and not other_series_raw:
                continue

            worknumber = goodreads_worknumber(session, author, title)
            if worknumber is None:
                goodreads_series = NO_MATCH
            else:
                goodreads_series = goodreads_seriesname(session, worknumber)

            record_series = field_490 + other_series_raw
            proper = has_proper_series(goodreads_series)
            if proper and series_matches(goodreads_series, record_series):
                continue

            # Only a Goodreads series name that differs from every series in the record is a mismatch
            if proper:
                mismatches += 1

            if args.brief and not proper:
                continue

            display_490 = "; ".join(field_490) if field_490 else "-"
            display_other = "; ".join(f"({tag}) {value}" for tag, value in other_series) if other_series else "-"
            display_goodreads = goodreads_series if goodreads_series else "-"

            emit_row(console, csv_writer, (title, author, display_490, display_other, display_goodreads), False)

        output_file.write("\n# " + "=" * 72 + "\n")
        for line in summary_lines(processed, skipped, mismatches):
            output_file.write(f"# {line}\n")

    print()
    for line in summary_lines(processed, skipped, mismatches):
        print(line)
    print("=" * 40)
    print(f"Detailed report written to: {args.output}\n")


if __name__ == "__main__":
    main()
