#
#    Reads records from a binary MARC file and, using the author and title information, gets series
#    information from Goodreads.  The Goodreads series name is compared
#    against the series information in the record's 490 field and its 800 $t, 810 $t, 811 $t and 830 $a
#    fields, if any.  A record is reported when at least one of these fields has a series name and the
#    Goodreads series name does not match any of them.
#
#    Usage:  python check-series.py -i <MARC input file> -o <output file> [-b]
#
#        -i,  --input     MARC input file (required)
#        -b,  --brief     only show rows with a proper Goodreads series name (not skipped, empty, or
#                         no match)
#        -o,  --output    Excel-compatible CSV output file (required). Terminal output is
#                         written to the terminal as well.
#
#    For each reported record, prints a table row as soon as it is generated (rather than waiting for
#    the whole file to be processed), with the 245a title, the 100a author, the 490a series names, the
#    series names from the 800 $t, 810 $t, 811 $t and 830 $a fields (each prefixed with its field tag,
#    e.g. "(830) Some Series"), and the Goodreads series name (last column).  A header is printed once,
#    and each row is printed as plain aligned text followed by a single rule line, so output prints and
#    scrolls normally in the terminal with exactly one line between rows.  A missing series name (record
#    field or Goodreads) is printed as '-', except that the Goodreads column is printed as 'no match'
#    when the author/title search finds no matching work on Goodreads.  A record with no 100 field is
#    shown as a row with 'None' in the author column and 'Skipped' in the Goodreads column.  Trailing
#    spaces, colons, periods, slashes and equals signs are stripped from the title.
#
#    Requires the `rich` package (for table output) in addition to `pymarc`, `requests` and `xmltodict`.
